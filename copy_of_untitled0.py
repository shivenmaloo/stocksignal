def create_sequences(X_values, y_values, lookback):

    X_seq = []
    y_seq = []

    for i in range(lookback, len(X_values)):
        X_seq.append(
            X_values[i-lookback:i]
        )
        y_seq.append(
            y_values[i]
        )

    return np.array(X_seq), np.array(y_seq)



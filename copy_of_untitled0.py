def create_features(df):

    data = df.copy()

    # -------------------------
    # Returns
    # -------------------------
    data["Return_1"] = np.log(
        data["Close"] / data["Close"].shift(1)
    )

    data["Return_5"] = np.log(
        data["Close"] / data["Close"].shift(5)
    )

    data["Return_20"] = np.log(
        data["Close"] / data["Close"].shift(20)
    )

    # -------------------------
    # Moving averages
    # -------------------------
    data["SMA_5"] = data["Close"].rolling(5).mean()
    data["SMA_10"] = data["Close"].rolling(10).mean()
    data["SMA_20"] = data["Close"].rolling(20).mean()
    data["SMA_50"] = data["Close"].rolling(50).mean()
    data["SMA_200"] = data["Close"].rolling(200).mean()

    data["Price_SMA20"] = data["Close"] / data["SMA_20"]
    data["Price_SMA50"] = data["Close"] / data["SMA_50"]
    data["Price_SMA200"] = data["Close"] / data["SMA_200"]

    # -------------------------
    # EMA
    # -------------------------
    data["EMA_12"] = data["Close"].ewm(span=12).mean()
    data["EMA_26"] = data["Close"].ewm(span=26).mean()

    data["MACD"] = data["EMA_12"] - data["EMA_26"]

    # -------------------------
    # Volatility
    # -------------------------
    data["Volatility_5"] = data["Return_1"].rolling(5).std()
    data["Volatility_20"] = data["Return_1"].rolling(20).std()
    data["Volatility_60"] = data["Return_1"].rolling(60).std()

    # -------------------------
    # RSI
    # -------------------------
    delta = data["Close"].diff()

    gain = delta.clip(lower=0)
    loss = -delta.clip(upper=0)

    avg_gain = gain.rolling(14).mean()
    avg_loss = loss.rolling(14).mean()

    rs = avg_gain / (avg_loss + 1e-10)

    data["RSI"] = 100 - (100 / (1 + rs))

    # -------------------------
    # Volume
    # -------------------------
    data["Volume_SMA20"] = data["Volume"].rolling(20).mean()

    data["Volume_Ratio"] = (
        data["Volume"] /
        (data["Volume_SMA20"] + 1e-10)
    )

    # -------------------------
    # High-low range
    # -------------------------
    data["Daily_Range"] = (
        data["High"] - data["Low"]
    ) / data["Close"]

    # -------------------------
    # Target = NEXT DAY return
    # -------------------------
    data["Target"] = np.log(
        data["Close"].shift(-1) / data["Close"]
    )

    data = data.replace([np.inf, -np.inf], np.nan)
    data = data.dropna()

    return data



def calculate_confidence_score(df):

    df = df.copy()

    # Normalize RMSE
    rmse_score = (
        1 -
        (
            df["RMSE"] /
            (df["RMSE"].max() + 1e-10)
        )
    )

    # Directional accuracy
    direction_score = df[
        "Directional_Accuracy"
    ]

    # R2 clipped to sensible range
    r2_score_component = (
        df["R2"].clip(-1, 1) + 1
    ) / 2

    # How close empirical coverage is to requested confidence
    coverage_score = 1 - (
        abs(
            df["Interval_Coverage"]
            - CONFIDENCE_LEVEL
        )
    )

    # Narrower interval gets a higher score
    width_score = (
        1 -
        (
            df["Interval_Width"] /
            (df["Interval_Width"].max() + 1e-10)
        )
    )

    df["Confidence_Score"] = (
        0.30 * rmse_score +
        0.25 * direction_score +
        0.15 * r2_score_component +
        0.20 * coverage_score +
        0.10 * width_score
    ) * 100

    return df



def conformal_interval(
    predictions,
    actuals,
    confidence=0.90
):

    predictions = np.asarray(predictions)
    actuals = np.asarray(actuals)

    residuals = np.abs(
        actuals - predictions
    )

    alpha = 1 - confidence

    q = np.quantile(
        residuals,
        1 - alpha
    )

    lower = predictions - q
    upper = predictions + q

    coverage = np.mean(
        (actuals >= lower) &
        (actuals <= upper)
    )

    avg_width = np.mean(
        upper - lower
    )

    return {
        "q": q,
        "coverage": coverage,
        "width": avg_width
    }

